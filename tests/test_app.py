"""App-level wiring: CORS, the favicon, and the live-data proxy.

CORS is asserted on error responses too, because those are generated by
Connexion's middleware rather than Flask -- which is why the middleware is
mounted on the ASGI stack (see igmk_api/app.py).
"""

import pytest
import requests
import responses
from conftest import write

ORIGIN = "https://browser.herz-campaigns.de"
LIVE_URL = "https://live.example.test/data.json"


def test_favicon_is_served(client):
    r = client.get("/favicon.ico")
    assert r.status_code == 200
    assert r.headers["content-type"] == "image/vnd.microsoft.icon"


@pytest.mark.parametrize("url,expected_status", [
    ("/sites", 200),
    ("/nosuchroute", 404),
    ("/sites/nosuchsite", 404),
    ("/visualizations/byID/x/hourly/20250101", 400),
])
def test_cors_headers_on_every_response_class(client, url, expected_status):
    r = client.get(url, headers={"Origin": ORIGIN})
    assert r.status_code == expected_status
    assert r.headers["access-control-allow-origin"] == ORIGIN


# --- /live proxy ------------------------------------------------------------


@pytest.fixture
def live_site(config_root):
    write(config_root / "sites", "live.yaml", {"name": "Live Site", "live_data": LIVE_URL})
    write(config_root / "sites", "nofeed.yaml", {"name": "No Feed"})
    write(config_root / "sites", "badurl.yaml", {"name": "Bad URL", "live_data": "not-a-url"})
    return config_root


@responses.activate
def test_live_data_is_proxied(client, live_site):
    responses.add(responses.GET, LIVE_URL, json={"temperature": 12.5}, status=200)
    r = client.get("/live/live")
    assert r.status_code == 200
    assert r.json() == {"temperature": 12.5}


@responses.activate
def test_live_data_upstream_error_is_503(client, live_site):
    responses.add(responses.GET, LIVE_URL, status=500)
    assert client.get("/live/live").status_code == 503


@responses.activate
def test_live_data_upstream_timeout_is_503(client, live_site):
    responses.add(responses.GET, LIVE_URL, body=requests.exceptions.ReadTimeout("slow"))
    assert client.get("/live/live").status_code == 503


@responses.activate
def test_live_data_invalid_json_is_502(client, live_site):
    responses.add(responses.GET, LIVE_URL, body="not json", status=200)
    assert client.get("/live/live").status_code == 502


@pytest.mark.parametrize("site,expected_status", [
    ("nofeed", 501),    # no liveDataPath at all
    ("badurl", 501),    # liveDataPath present but not a URL
    ("absent", 404),
])
def test_live_data_unusable_feeds(client, live_site, site, expected_status):
    assert client.get(f"/live/{site}").status_code == expected_status
